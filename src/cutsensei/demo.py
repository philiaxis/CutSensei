class _Board:
    def __init__(self, spec: DemoSpec, rng: np.random.Generator) -> None:
        w, h = spec.width, spec.height
        self.rng = rng
        self.x0, self.y0 = int(w * 0.08), int(h * 0.08)
        self.x1, self.y1 = int(w * 0.92), int(h * 0.72)
        base = np.zeros((h, w, 3), np.uint8)
        base[:] = (150, 150, 145)                          # wall (BGR)
        base[int(h * 0.72):] = (95, 105, 110)              # floor
        base[self.y0:self.y1, self.x0:self.x1] = (52, 78, 44)  # dark green board
        base[self.y1:self.y1 + 6, self.x0 - 4:self.x1 + 4] = (60, 60, 60)  # chalk tray
        self.base = base
        self.ink = np.zeros((h, w), np.uint8)
        # writing cursor (text lines)
        self.cx = self.x0 + 20
        self.cy = self.y0 + 30
        self.pen = np.array([self.cx, self.cy], float)

    def write_step(self, amount: float) -> Tuple[int, int]:
        """Advance the "handwriting" by ``amount`` pixels of stroke."""
        import cv2

        remaining = amount
        while remaining > 0:
            if self.rng.random() < 0.08:
                # new glyph: jump right
                self.cx += int(self.rng.integers(12, 22))
                if self.cx > self.x1 - 40:
                    self.cx = self.x0 + 20
                    self.cy += 34
                    if self.cy > self.y1 - 30:
                        self.cy = self.y0 + 30
                        self.ink[:] = 0  # board wiped (should not happen in tests)
                self.pen = np.array([self.cx + self.rng.uniform(0, 8),
                                     self.cy + self.rng.uniform(-10, 10)])
            step = self.rng.uniform(2, 5)
            angle = self.rng.uniform(0, 2 * np.pi)
            nxt = self.pen + step * np.array([np.cos(angle), np.sin(angle)])
            nxt[0] = np.clip(nxt[0], self.cx - 2, self.cx + 16)
            nxt[1] = np.clip(nxt[1], self.cy - 12, self.cy + 12)
            cv2.line(self.ink, tuple(int(v) for v in self.pen), tuple(int(v) for v in nxt), 1, 2)
            self.pen = nxt
            remaining -= step
        return int(self.pen[0]), int(self.pen[1])


def _draw_person(frame: np.ndarray, x: float, h: int, arm_to: Optional[Tuple[int, int]],
                 bob: float) -> None:
    import cv2

    body_top = int(h * 0.42 + bob)
    cx = int(x)
    cv2.rectangle(frame, (cx - 28, body_top), (cx + 28, h - 1), (70, 40, 40), -1)  # coat
    cv2.circle(frame, (cx, body_top - 22), 20, (150, 175, 215), -1)                 # head
    cv2.circle(frame, (cx, body_top - 30), 20, (40, 35, 30), -1, lineType=cv2.LINE_AA)
    cv2.circle(frame, (cx, body_top - 18), 17, (150, 175, 215), -1)
    if arm_to is not None:
        cv2.line(frame, (cx + 20, body_top + 12), arm_to, (70, 40, 40), 9)
        cv2.circle(frame, arm_to, 6, (150, 175, 215), -1)
    else:
        cv2.line(frame, (cx + 22, body_top + 12), (cx + 30, body_top + 80), (70, 40, 40), 9)


def generate_demo(path: str, spec: Optional[DemoSpec] = None,
                  crf: int = 26) -> DemoSpec:
    """Render the demo lecture to ``path`` (mp4, H.264 + AAC)."""
    import os
    import tempfile
    import wave

    spec = spec or DemoSpec()
    rng = np.random.default_rng(spec.seed)
    audio = synth_audio(spec)
    fd, wav_path = tempfile.mkstemp(suffix=".wav")
    os.close(fd)
    with wave.open(wav_path, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(AUDIO_SR)
        wf.writeframes((audio * 32767).astype("<i2").tobytes())

    w, h, fps = spec.width, spec.height, spec.fps
    cmd = [ffmpeg.find_ffmpeg(), "-hide_banner", "-loglevel", "error", "-y",
           "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{w}x{h}", "-r", str(fps),
           "-i", "pipe:0", "-i", wav_path, "-c:v", "libx264", "-preset", "veryfast",
           "-crf", str(crf), "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "128k",
           "-shortest", path]
    proc = ffmpeg.popen(cmd, stdin=subprocess.PIPE)
    board = _Board(spec, rng)
    # pre-computed sensor noise (cycled; cheaper than fresh noise per frame)
    noise_bank = [rng.normal(0, 2.0, (h, w, 3)).round().astype(np.int16) for _ in range(7)]
    person_x = w * 0.3
    target_x = person_x
    arm: Optional[Tuple[int, int]] = None
    try:
        total_frames = int(round(spec.duration * fps))
        ranges = spec.scene_ranges()
        for fi in range(total_frames):
            t = fi / fps
            kind = next((k for k, a, b in ranges if a <= t < b), ranges[-1][0])
            bob = 0.0
            arm = None
            if kind in ("writing", "speech_writing"):
                # stand next to the writing position and move the hand
                target_x = min(max(board.cx - 45, w * 0.12), w * 0.85)
                pen = board.write_step(rng.uniform(1.5, 4.0) if rng.random() > 0.05 else 0)
                arm = (pen[0], pen[1])
                bob = 1.5 * math.sin(t * 5)
            elif kind == "speech":
                target_x = w * 0.3 + 40 * math.sin(t * 0.3)
                bob = 2.0 * math.sin(t * 3)
                if (t % 7) < 2.0:
                    arm = (int(person_x + 60), int(h * 0.35 + 10 * math.sin(t * 4)))
            elif kind == "walk":
                target_x = w * 0.15 + (w * 0.7) * (0.5 + 0.5 * math.sin(t * 0.4))
                bob = 3.0 * abs(math.sin(t * 6))
            else:  # idle: stand still
                bob = 0.0
            person_x += (target_x - person_x) * 0.08
            frame = board.base.copy()
            frame[board.ink.astype(bool)] = (225, 228, 230)
            _draw_person(frame, person_x, h, arm, bob)
            noise = noise_bank[fi % len(noise_bank)]
            frame = np.clip(frame.astype(np.int16) + noise, 0, 255).astype(np.uint8)
            assert proc.stdin is not None
            proc.stdin.write(frame.tobytes())
        assert proc.stdin is not None
        proc.stdin.close()
        if proc.wait() != 0:
            raise RuntimeError("ffmpeg failed while encoding the demo video")
    finally:
        if proc.poll() is None:
            proc.kill()
        try:
            os.unlink(wav_path)
        except OSError:
            pass
    return spec


def board_region(spec: DemoSpec) -> List[float]:
    """Normalized board rectangle of the demo video."""
    return [0.08, 0.08, 0.84, 0.64]
