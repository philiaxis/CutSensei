"""Synthetic lecture video generator.

Creates a fixed-camera "lecture" with a board, a lecturer, synthetic speech,
chalk sounds and strokes that appear on the board.  It is used by the test
suite (including the 60 s / 40 s / 20 s acceptance scenario of the design
document) and can be generated by users to try the application::

    cutsensei-cli demo lecture.mp4
"""

from __future__ import annotations

import math
import subprocess
from dataclasses import dataclass, field
from typing import List, Optional, Tuple

import numpy as np

from .core import ffmpeg

AUDIO_SR = 48000


@dataclass
class Scene:
    kind: str          # "speech", "speech_writing", "writing", "idle", "walk"
    duration: float


@dataclass
class DemoSpec:
    scenes: List[Scene] = field(default_factory=lambda: [
        Scene("speech", 60.0), Scene("writing", 40.0), Scene("idle", 20.0)])
    width: int = 640
    height: int = 360
    fps: int = 30
    seed: int = 7

    @property
    def duration(self) -> float:
        return sum(s.duration for s in self.scenes)

    def scene_ranges(self) -> List[Tuple[str, float, float]]:
        out, t = [], 0.0
        for s in self.scenes:
            out.append((s.kind, t, t + s.duration))
            t += s.duration
        return out


# ----------------------------------------------------------------------------
# audio
# ----------------------------------------------------------------------------

_VOWELS = [  # (F1, F2, F3) in Hz
    (730, 1090, 2440), (270, 2290, 3010), (300, 870, 2240), (530, 1840, 2480),
    (570, 840, 2410), (440, 1020, 2240), (660, 1720, 2410),
]


def _speech(duration: float, rng: np.random.Generator, sr: int = AUDIO_SR) -> np.ndarray:
    """Additive synthesis of a speech-like signal (syllables with pitch)."""
    n = int(duration * sr)
    out = np.zeros(n, np.float32)
    t = 0.0
    while t < duration - 0.2:
        # a "word" of 2-5 syllables
        for _ in range(int(rng.integers(2, 6))):
            syl = float(rng.uniform(0.14, 0.26))
            if t + syl >= duration:
                break
            i0, i1 = int(t * sr), int((t + syl) * sr)
            m = i1 - i0
            tt = np.arange(m) / sr
            f0 = rng.uniform(105, 175) * (1 + 0.12 * np.sin(2 * np.pi * rng.uniform(1, 3) * tt))
            phase = 2 * np.pi * np.cumsum(f0) / sr
            f1, f2, f3 = _VOWELS[int(rng.integers(len(_VOWELS)))]
            sig = np.zeros(m)
            for k in range(1, 30):
                fk = k * f0
                amp = (np.exp(-((fk - f1) / 110) ** 2) + 0.6 * np.exp(-((fk - f2) / 160) ** 2)
                       + 0.3 * np.exp(-((fk - f3) / 220) ** 2) + 0.02)
                amp = np.where(fk < sr / 2 - 500, amp, 0) / k ** 0.5
                sig += amp * np.sin(k * phase)
            env = np.sin(np.pi * np.clip(tt / syl, 0, 1)) ** 0.6
            out[i0:i1] += (0.22 * env * sig / (np.abs(sig).max() + 1e-9)).astype(np.float32)
            # an unvoiced consonant after some syllables
            if rng.random() < 0.4:
                c0 = i1
                c1 = min(n, c0 + int(rng.uniform(0.03, 0.07) * sr))
                noise = rng.normal(0, 1, c1 - c0)
                noise = np.diff(np.concatenate([[0.0], noise]))
                out[c0:c1] += (0.02 * noise).astype(np.float32)
            t += syl + float(rng.uniform(0.02, 0.07))
        t += float(rng.uniform(0.12, 0.45))  # pause between words
    return out


def _chalk(duration: float, rng: np.random.Generator, sr: int = AUDIO_SR,
           rate: Tuple[float, float] = (3.0, 7.0)) -> np.ndarray:
    """Impulsive chalk taps and short scratches."""
    n = int(duration * sr)
    out = np.zeros(n, np.float32)
    t = float(rng.uniform(0.1, 0.4))
    while t < duration - 0.05:
        i0 = int(t * sr)
        length = int(rng.uniform(0.004, 0.015) * sr)
        burst = rng.normal(0, 1, length)
        burst = np.diff(np.concatenate([[0.0], burst]))  # high-pass
        burst *= np.exp(-np.arange(length) / (length / 4))
        out[i0:i0 + length] += (rng.uniform(0.08, 0.25) * burst[: n - i0]).astype(np.float32)
        t += float(rng.exponential(1.0 / rng.uniform(*rate)))
        if rng.random() < 0.05:
            t += float(rng.uniform(0.5, 1.5))  # thinking pause
    return out


def _room(n: int, rng: np.random.Generator, sr: int = AUDIO_SR) -> np.ndarray:
    white = rng.normal(0, 1, n)
    # cheap pink-ish noise
    pink = np.convolve(white, np.ones(8) / 8, mode="same")
    hum = 0.3 * np.sin(2 * np.pi * 50 * np.arange(n) / sr)
    return (0.0015 * (pink + hum)).astype(np.float32)


def synth_audio(spec: DemoSpec) -> np.ndarray:
    rng = np.random.default_rng(spec.seed)
    n = int(spec.duration * AUDIO_SR)
    audio = _room(n, rng)
    for kind, a, b in spec.scene_ranges():
        i0, i1 = int(a * AUDIO_SR), int(b * AUDIO_SR)
        if kind in ("speech", "speech_writing"):
            audio[i0:i1] += _speech(b - a, rng)[: i1 - i0]
        if kind in ("writing", "speech_writing"):
            audio[i0:i1] += _chalk(b - a, rng)[: i1 - i0]
        if kind == "walk":
            # footsteps: soft low thumps
            t = 0.3
            while t < b - a - 0.2:
                j = i0 + int(t * AUDIO_SR)
                m = int(0.05 * AUDIO_SR)
                thump = np.sin(2 * np.pi * 90 * np.arange(m) / AUDIO_SR) * \
                    np.exp(-np.arange(m) / (0.012 * AUDIO_SR))
                audio[j:j + m] += (0.03 * thump).astype(np.float32)
                t += 0.55
    return np.clip(audio, -1, 1)


